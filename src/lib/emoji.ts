export const LIST_EMOJI: Record<ListId, string> = {
  grocery: '🛒',
  important: '📌',
}

export function emojiFor(name: string, list: ListId): string {
  const k = name.toLocaleLowerCase()
  for (const [re, e] of TABLE) if (re.test(k)) return e
  return LIST_EMOJI[list]
}
